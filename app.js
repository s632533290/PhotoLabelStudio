const english = translations["en-US"];
const supported = Object.keys(translations);
const aliases = { de: "de-DE", es: "es-ES", fr: "fr-FR", pt: "pt-BR", "zh-CN": "zh-Hans", "zh-TW": "zh-Hant", "zh-HK": "zh-Hant" };
const params = new URLSearchParams(window.location.search);
const requested = params.get("lang");
const browserLanguage = (navigator.languages || [navigator.language || "en-US"]).map((value) => value.replace(/_/g, "-"));
const activeLocale = supported.includes(requested) ? requested : browserLanguage.find((value) => supported.includes(value) || aliases[value]) || "en-US";
const locale = aliases[activeLocale] || activeLocale;
const regionalBase = { "es-MX": "es-ES" };
const copy = { ...english, ...(translations[regionalBase[locale]] || {}), ...translations[locale] };

document.documentElement.lang = locale;
document.title = "Photo Label Studio";
document.querySelector('meta[name="description"]').content = copy.lead;
document.getElementById("year").textContent = new Date().getFullYear();

for (const [key, value] of Object.entries(copy)) {
  if (key === "privacyFacts" || key === "name") continue;
  document.querySelectorAll(`[data-i18n="${key}"]`).forEach((element) => { element.textContent = value; });
}

const facts = document.getElementById("privacy-facts");
facts.replaceChildren();
copy.privacyFacts.forEach((fact) => { const item = document.createElement("li"); item.textContent = fact; facts.appendChild(item); });

const picker = document.getElementById("language");
supported.forEach((value) => { const option = document.createElement("option"); option.value = value; option.textContent = translations[value].name; option.selected = value === locale; picker.appendChild(option); });

function localizedHref(section) { return `./?lang=${encodeURIComponent(locale)}#${section}`; }
document.querySelectorAll("[data-nav]").forEach((link) => {
  const section = link.dataset.nav;
  link.href = section === "privacy" ? `./privacy/?lang=${encodeURIComponent(locale)}` : localizedHref(section);
});
document.querySelector(".brand").href = localizedHref("marketing");

picker.addEventListener("change", (event) => {
  const section = window.location.hash || "#marketing";
  window.location.assign(`./?lang=${encodeURIComponent(event.target.value)}${section}`);
});
